package io.github.lucasclgibson.nimbus.data.source

import io.github.lucasclgibson.nimbus.core.now
import java.time.Instant
import java.time.ZoneId

/**
 * Builds catch-up / "watch from start" URLs for M3U channels, following the conventions used by
 * Kodi's pvr.iptvsimple (catchup="default|append|shift|flussonic|xc" + catchup-source templates).
 */
object Catchup {

    fun build(
        type: String,
        source: String,
        liveUrl: String,
        startMs: Long,
        endMs: Long,
        zone: ZoneId = ZoneId.systemDefault(),
    ): String? {
        val t = type.lowercase()
        return when {
            t == "shift" || t == "timeshift" -> {
                val sep = if (liveUrl.contains('?')) '&' else '?'
                fill("$liveUrl${sep}utc={utc}&lutc={lutc}", startMs, endMs, zone)
            }
            t == "flussonic" || t == "flussonic-hls" || t == "flussonic-ts" || t == "fs" -> flussonic(liveUrl, startMs, endMs)
            t == "xc" -> xtreamFromUrl(liveUrl, startMs, endMs, zone)
            t == "append" -> if (source.isNotBlank()) liveUrl + fill(source, startMs, endMs, zone) else null
            t == "default" || t == "" || t == "vod" -> when {
                source.isBlank() -> null
                source.startsWith("http", ignoreCase = true) -> fill(source, startMs, endMs, zone)
                else -> liveUrl + fill(source, startMs, endMs, zone)
            }
            else -> if (source.isNotBlank()) fill(source, startMs, endMs, zone) else null
        }
    }

    private val formatToken = Regex("""\{(utc|start|utcend|end|lutc|now|timestamp|duration|offset)(?::([^}]*))?\}""")

    fun fill(template: String, startMs: Long, endMs: Long, zone: ZoneId): String {
        val start = startMs / 1000
        val end = endMs / 1000
        val nowS = now() / 1000
        val local = Instant.ofEpochMilli(startMs).atZone(zone)
        val localEnd = Instant.ofEpochMilli(endMs).atZone(zone)
        var s = template.replace("\${", "{")
        s = formatToken.replace(s) { m ->
            val key = m.groupValues[1]
            val arg = m.groups[2]?.value
            when (key) {
                "utc", "start" -> if (arg != null) dateFormat(arg, local.toEpochSecond(), zone) else start.toString()
                "utcend", "end" -> if (arg != null) dateFormat(arg, localEnd.toEpochSecond(), zone) else end.toString()
                "lutc", "now", "timestamp" -> if (arg != null) dateFormat(arg, nowS, zone) else nowS.toString()
                "duration" -> {
                    val div = arg?.toLongOrNull()?.takeIf { it > 0 } ?: 1
                    ((end - start) / div).toString()
                }
                "offset" -> {
                    val div = arg?.toLongOrNull()?.takeIf { it > 0 } ?: 1
                    ((nowS - start) / div).toString()
                }
                else -> m.value
            }
        }
        s = s.replace("{Y}", "%04d".format(local.year))
            .replace("{m}", "%02d".format(local.monthValue))
            .replace("{d}", "%02d".format(local.dayOfMonth))
            .replace("{H}", "%02d".format(local.hour))
            .replace("{M}", "%02d".format(local.minute))
            .replace("{S}", "%02d".format(local.second))
        return s
    }

    /** Format with Y m d H M S tokens, e.g. "Y-m-d:H-M". */
    private fun dateFormat(pattern: String, epochSec: Long, zone: ZoneId): String {
        val t = Instant.ofEpochSecond(epochSec).atZone(zone)
        val sb = StringBuilder()
        for (c in pattern) {
            sb.append(
                when (c) {
                    'Y' -> "%04d".format(t.year)
                    'm' -> "%02d".format(t.monthValue)
                    'd' -> "%02d".format(t.dayOfMonth)
                    'H' -> "%02d".format(t.hour)
                    'M' -> "%02d".format(t.minute)
                    'S' -> "%02d".format(t.second)
                    else -> c.toString()
                }
            )
        }
        return sb.toString()
    }

    private fun flussonic(url: String, startMs: Long, endMs: Long): String? {
        val start = startMs / 1000
        val duration = (endMs - startMs) / 1000
        val m = Regex("""^(https?://[^/]+)/(.*)/([^/?]*?)(mpegts|\.m3u8)(\?.*)?$""").find(url) ?: return null
        val host = m.groupValues[1]
        val path = m.groupValues[2]
        val file = m.groupValues[3]
        val kind = m.groupValues[4]
        val query = m.groups[5]?.value.orEmpty()
        return if (kind == "mpegts") {
            "$host/$path/timeshift_abs-$start.ts$query"
        } else {
            val name = file.ifBlank { "index" }
            "$host/$path/$name-$start-$duration.m3u8$query"
        }
    }

    /** M3U playlists generated by Xtream panels: http://host/(live/)user/pass/123(.ts) */
    private fun xtreamFromUrl(url: String, startMs: Long, endMs: Long, zone: ZoneId): String? {
        val m = Regex("""^(https?://[^/]+)/(?:live/)?([^/]+)/([^/]+)/(\d+)(\.[a-z0-9]+)?$""", RegexOption.IGNORE_CASE)
            .find(url.substringBefore('?')) ?: return null
        val (host, user, pass, id) = m.destructured
        val durationMin = ((endMs - startMs) / 60_000).coerceAtLeast(1)
        val start = Instant.ofEpochMilli(startMs).atZone(zone)
        val stamp = "%04d-%02d-%02d:%02d-%02d".format(start.year, start.monthValue, start.dayOfMonth, start.hour, start.minute)
        return "$host/timeshift/$user/$pass/$durationMin/$stamp/$id.ts"
    }
}
